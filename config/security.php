<?php

/**
 * 安全模块配置
 *
 * 所有默认值都倾向"安全优先"——开发者需要时才关闭。
 *
 * 覆盖方式：
 *   1. 修改本文件的默认值（提交进仓库影响全员）
 *   2. 在 .env 中配置同名环境变量（不影响代码，部署级覆盖）
 *   3. 在 config/prod/security.php 中覆盖（环境级覆盖，prod 环境专用）
 */

return [
    // ----------------------------------------------------------------
    //  安全响应头（在 RequestHandler 默认注入到所有响应）
    // ----------------------------------------------------------------
    // 单项设为 false / null 可关闭该项；设为字符串可覆盖默认值
    'headers' => [
        'X-Content-Type-Options' => 'nosniff',
        'X-Frame-Options' => 'SAMEORIGIN',
        'Referrer-Policy' => 'no-referrer-when-downgrade',
        'X-XSS-Protection' => '1; mode=block',
    ],

    // ----------------------------------------------------------------
    //  JSON 安全编码（防止 <script> 注入到 JSON 字符串）
    // ----------------------------------------------------------------
    // 启用后 Response::withJson 会附加 JSON_HEX_TAG|JSON_HEX_APOS|JSON_HEX_QUOT|JSON_HEX_AMP
    // 前端 JSON.parse 后仍是原字符，但浏览器不会把 JSON 里的 <script> 误解析为标签
    'json_safety' => env('SECURITY_JSON_SAFETY', true),

    // ----------------------------------------------------------------
    //  输入自动净化（null byte / 控制字符）
    // ----------------------------------------------------------------
    // 启用后 Request::input / all 等便利方法会自动调用 InputSanitizer::clean
    'input_sanitizer' => env('SECURITY_INPUT_SANITIZER', true),

    // ----------------------------------------------------------------
    //  bcrypt cost（4-31）
    // ----------------------------------------------------------------
    // 建议生产环境 10-12；过高（>12）会显著拖慢请求
    // 每次升 1，哈希时间约翻倍
    'bcrypt_cost' => env('BCRYPT_COST', 10),

    // ----------------------------------------------------------------
    //  对称加密算法
    // ----------------------------------------------------------------
    // 当前固定 aes-256-gcm（带 GCM 认证标签）
    // APP_KEY 通过 `php bin/sikelan security:key` 生成，写入 .env
    'cipher' => 'aes-256-gcm',
];
